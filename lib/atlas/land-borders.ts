function pairKey(a: string, b: string): string {
  return a < b ? `${a}|${b}` : `${b}|${a}`;
}

/** Exported for the self-check to assert row counts and shape against, not re-typed. */
export const LAND_BORDER_PAIRS: ReadonlySet<string> = new Set(
  RAW_PAIRS.map(([a, b]) => pairKey(a, b))
);

/** True only for two ISO3 codes that share a real land boundary. */
export function isLandBorder(a: string, b: string): boolean {
  return LAND_BORDER_PAIRS.has(pairKey(a, b));
}

// Real land borders — every unordered ISO3 pair that actually shares a land
// boundary, including a handful of dependent-territory ones a quiz question
// would otherwise miss (GIB-ESP, GUF-SUR, MAF-SXM).
//
// WHY THIS EXISTS
//
// Wikidata's P47 ("shares border with"), the source
// lib/atlas/sources/wikidata.ts's fetchNeighbours pulls from, is broader
// than a land border. It also carries maritime and disputed relationships —
// "Maldives shares a border with United Kingdom" (the Chagos Archipelago
// dispute), "Kiribati shares a border with United States" (a shared claim
// over a Pacific atoll), "Sudan shares a border with Uganda" (true before
// South Sudan split off in 2011, false since). None of that is a Wikidata
// mistake — P47's own documentation covers maritime borders too — it's the
// wrong property for a "these two countries are next to each other on land"
// quiz clue.
//
// Checked directly against query.wikidata.org (2026-08-08): no qualifier on
// any country's P47 statement distinguishes land from maritime. Sampled
// Maldives-UK specifically and swept every qualifier property used on any
// P47 statement anywhere — start/end date, statement length, a handful of
// single-use ones — none of them mark border type. So there is no way to
// filter P47 by asking Wikidata a sharper question; a second, independent
// reference is the only fix that doesn't wait on hand-verifying ~450 pairs.
//
// This table is that reference: land-border pairs from mledoze/countries
// (github.com/mledoze/countries)'s `borders` field, which descends from the
// CIA World Factbook — the same data restcountries.com serves — captured
// 2026-08-08. Kosovo (mledoze's code "UNK") is remapped to this repo's XKX.
// Only pairs where both ISO3s are in lib/atlas/iso-countries.ts are kept.
//
// build-deck.mjs's buildCountry() uses this to filter, never to add: a
// Wikidata-sourced neighbour survives into deck.json only if it's also
// here. It's deliberately the full ~325-pair world table, not trimmed down
// to just the ~450 pairs the current snapshot happens to assert — so a
// true border the snapshot is missing today (Norway-Russia isn't in any
// committed snapshot's P47 result, but is a real, short land border, and is
// in this table) still works the day the snapshot catches up, without
// anyone having to touch this file again.
//
// One hand-verified correction on top of mledoze: its `borders` field lists
// IND-LKA (India-Sri Lanka) as a land border. Sri Lanka is an island — the
// Palk Strait separates it from India, no land crossing exists — so that
// pair is deliberately left out below rather than carried over. Everything
// else here is mledoze's data unmodified; re-check this table by hand
// before trusting a new pair that looks similarly implausible.
